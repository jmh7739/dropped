const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const moduleResult = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/retail.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText,
  { exports: moduleResult.exports, module: moduleResult, Date, Intl, URL, URLSearchParams, Set, Number, Object, JSON });
const m = moduleResult.exports;
const now = Date.parse('2026-10-21T13:10:00Z');
const catalog = JSON.parse(fs.readFileSync('data/retail-promotions.json', 'utf8'));
assert.equal(m.validCatalog(catalog, Math.max(now, Date.parse(catalog.checkedAt)+1000)), true, 'only genuine validated snapshots');
const o = catalog.offers[0];
assert.deepEqual(JSON.parse(JSON.stringify(m.bundlePrice({unitPrice:1000,buyQuantity:2,giftQuantity:1}))), {total:2000,quantity:3,each:2000/3});
assert.equal(m.bundlePrice({unitPrice:1000,buyQuantity:0,giftQuantity:1}), null);
assert.equal(m.offerStatus({...o,lastSeenAt:'2026-10-18T00:00:00Z'},now),'old');
assert.equal(m.offerStatus({...o,endDate:'2026-10-20'},now),'ended');
assert.equal(m.offerStatus({...o,startDate:'2026-10-22'},now),'upcoming');
assert.equal(m.offerStatus({...o,lastSeenAt:'2026-10-22T00:00:00Z'},now),'old');
assert.equal(m.offerStatus({...o,endDate:'2026-10-21'},now),'current','date-only end covers that KST calendar day without inventing a time');
assert.equal(m.filterOffers([o], {...m.EMPTY_FILTERS,period:'week'},now).length,0,'unknown end is excluded from deadline filter');
assert.equal(m.filterOffers([o], {...m.EMPTY_FILTERS,q:'NO-SUCH-ITEM'},now).length,0);
assert.equal(m.filterOffers([o], {...m.EMPTY_FILTERS,brand:'gs25'},now).length,0);
assert.equal(m.previousPrice(o),null,'first collection has no invented comparison');
const h={...o,name:o.name,barcode:o.barcode,unitPrice:2000,buyQuantity:1,giftQuantity:1,checkedAt:'2026-10-20T00:00:00Z',revision:'older'};
assert.ok(m.previousPrice({...o,history:[h,...o.history]}));
assert.equal(m.previousPrice({...o,history:[{...h,name:'different product'},...o.history]}),null,'SKU reuse must not compare different products');
assert.equal(m.validCatalog({...catalog,checkedAt:'2026-10-22T00:00:00Z'},now),false);
assert.equal(m.validCatalog({...catalog,offers:[{...o,sourceUrl:'https://example.com/'}]},now),false);
assert.equal(m.validCatalog({...catalog,offers:[o,o]},now),false);
assert.equal(m.validCatalog({...catalog,offers:[{...o,endDate:'2026-13-99'}]},now),false);
assert.equal(m.validCatalog({...catalog,offers:[{...o,unitPrice:-1}]},now),false);
assert.equal(m.parsePreferences('{broken').favorites.length,0);
assert.equal(m.parsePreferences('null').favorites.length,0);
assert.equal(m.parsePreferences(JSON.stringify({cart:{[o.id]:-1},favorites:[o.id,o.id],brands:['nobrand','untrusted']})).favorites.length,1);
assert.equal(Object.keys(m.parsePreferences(JSON.stringify({cart:{[o.id]:51}})).cart).length,0);
assert.equal(m.readFilters(new URLSearchParams('period=bad&brand=bad&type=bad')).period,'current');
assert.equal(m.readFilters(new URLSearchParams('brand=nobrand')).brand,'nobrand');
assert.equal(m.isPublishableRetailOffer({...o,id:'homeplus-2645',startDate:'2026-10-15',endDate:'2026-10-21'}),false,'contradictory original prices stay under review');
assert.equal(m.isPublishableRetailOffer({...o,id:'homeplus-2645',startDate:'2026-10-22',endDate:'2026-10-28'}),true,'a hold is limited to the actual conflicting period');
assert.equal(m.parsePreferences(JSON.stringify({favorites:['homeplus-2756'],cart:{'homeplus-2756':2}})).cart['homeplus-2756'],2);
console.log('Retail quantity, dates, history identity, source validation and damaged-storage checks passed');
